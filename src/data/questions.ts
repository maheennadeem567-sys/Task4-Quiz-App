/**
 * Returns all categories belonging to the selected audience (General or Children).
 */
export function getCategoriesByAudience(audience: AudienceType): CategoryInfo[] {
  return CATEGORIES.filter((c) => c.audience === audience);
}

/**
 * Retrieves the 10 questions for a specific category.
 */
export function getQuestionsByCategory(categoryId: CategoryKey): Question[] {
  return ALL_QUESTIONS.filter((q) => q.category === categoryId);
}

/**
 * Returns CategoryInfo for the given category key.
 */
export function getCategoryById(categoryId: CategoryKey): CategoryInfo {
  const cat = CATEGORIES.find((c) => c.id === categoryId);
  return cat || CATEGORIES[0];
}

/**
 * Shuffles an array of questions randomly (Fisher-Yates shuffle) for a fresh quiz experience.
 */
export function shuffleQuestions(questions: Question[]): Question[] {
  const array = [...questions];
  for (let i = array.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }
  return array;
}
